/* ----------------------------------------------------------
   applyLang(code) — áp dụng bản dịch vào trang hiện tại
   ---------------------------------------------------------- */
(() => {
  const I = window.AN_THOI_I18N;
  const orig = new WeakMap();           // phần tử -> { vi: chữ gốc, key } | null
  const origPlaceholders = new WeakMap(); // input/textarea -> { vi: placeholder gốc, key } | null
  let index = null;                     // chữ tiếng Việt gốc -> khóa
  let titleVI = null;                   // <title> gốc của trang

  const norm = s => String(s || "").replace(/\s+/g, " ").trim();

  /* Trang hiện tại -> khóa dùng làm tiêu đề tab */
  const PAGE_TITLE = {
    "ve-chung-toi": "nav_about",
    "thuc-don": "nav_menu",
    "trai-nghiem": "nav_experience",
    "blog": "nav_blog",
    "lien-he": "nav_visit_full",
    "dat-ban": "btn_book"
  };
  const path = location.pathname;
  const slug = Object.keys(PAGE_TITLE).find(k => path.includes(k));
  const isArticle = path.includes("bai-viet");
  const isHome = !slug && !isArticle;

  const buildIndex = () => {
    index = Object.create(null);
    Object.keys(I.VI).forEach(k => {
      if (k.startsWith("doc_") || k === "footer_rm" || k === "footer_rm_on") return;
      const t = norm(I.VI[k]);
      if (t && !(t in index)) index[t] = k;
    });
  };

  /* Ghi nhớ chữ gốc + khóa của phần tử */
  const record = el => {
    if (orig.has(el)) return orig.get(el);
    let rec = null;
    if (el.dataset.i18n) {
      rec = { vi: el.textContent, key: el.dataset.i18n };
    } else {
      const key = index[norm(el.textContent)];
      if (key) rec = { vi: el.textContent, key };
    }
    orig.set(el, rec);
    return rec;
  };

  const LEAF = "a,span,h1,h2,h3,h4,p,li,label,dt,dd,option,button,small";
  const targets = () => {
    const out = [...document.querySelectorAll("[data-i18n]")];
    document.querySelectorAll(LEAF).forEach(el => {
      if (el.hasAttribute("data-i18n") || el.children.length) return;
      if (el.closest("#reduceMotion, .lang-select, script, style")) return;
      out.push(el);
    });
    return out;
  };

  /* Xử lý dịch placeholder */
  const handlePlaceholders = (code, T) => {
    document.querySelectorAll("input[placeholder], textarea[placeholder]").forEach(el => {
      if (!origPlaceholders.has(el)) {
        const ph = norm(el.getAttribute("placeholder"));
        let key = el.dataset.i18nPh || index[ph];
        origPlaceholders.set(el, { vi: el.getAttribute("placeholder"), key });
      }
      const rec = origPlaceholders.get(el);
      if (!rec || !rec.key) return;
      const newPh = code === "VI" ? rec.vi : (T[rec.key] !== undefined ? T[rec.key] : rec.vi);
      el.setAttribute("placeholder", newPh);
    });
  };

  const setTitle = (code, T) => {
    if (titleVI === null) titleVI = document.title;
    if (isArticle) return;
    if (code === "VI") document.title = titleVI;
    else if (isHome) document.title = T.doc_title;
    else document.title = (T[PAGE_TITLE[slug]] || "") + " - Ăn Thôi";
  };

  window.applyLang = function (code) {
    const T = I[code];
    if (!T) return;
    if (!index) buildIndex();

    window.AN_THOI_LANG = code;
    document.documentElement.lang = T.doc_lang;

    targets().forEach(el => {
      const rec = record(el);
      if (!rec || !rec.key) return;
      const txt = code === "VI" ? rec.vi : (T[rec.key] !== undefined ? T[rec.key] : rec.vi);
      el.textContent = txt;
    });

    handlePlaceholders(code, T);
    setTitle(code, T);

    try { localStorage.setItem("anthoi-lang", code); } catch (e) {}
  };
})();
