/* ----------------------------------------------------------
   applyLang(code) — áp dụng bản dịch vào trang
   ---------------------------------------------------------- */
window.applyLang = function(code) {
  const T = window.AN_THOI_I18N[code];
  if (!T) return;

  /* Cập nhật lang attribute + title */
  document.documentElement.lang = T.doc_lang;
  document.title = T.doc_title;

  /* Dịch tất cả [data-i18n] */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (T[key] !== undefined) el.textContent = T[key];
  });

  /* Lưu lựa chọn */
  try { localStorage.setItem('anthoi-lang', code); } catch(e) {}
};
